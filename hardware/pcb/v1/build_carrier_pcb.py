def add_fp(lib, nick, name, ref, value, x, y, rot=0.0):
    fp = pcbnew.FootprintLoad(lib, name)
    if fp is None:
        raise SystemExit("footprint not found: %s / %s" % (lib, name))
    fp.SetFPID(pcbnew.LIB_ID(nick, name))
    fp.SetReference(ref)
    fp.SetValue(value)
    board.Add(fp)
    fp.SetPosition(P(x, y))
    fp.SetOrientationDegrees(rot)
    return fp


def stock(lib, name, ref, value, x, y, rot=0.0):
    return add_fp(os.path.join(KICAD_FP, lib + ".pretty"), lib, name, ref, value, x, y, rot)


def pads(fp):
    return {p.GetNumber(): p for p in fp.Pads()}


def xy(pad):
    p = pad.GetPosition()
    return (round(ToMM(p.x) - OX, 3), round(ToMM(p.y) - OY, 3))


def resize(pad, dia, drill):
    size = VECTOR2I(FromMM(dia), FromMM(dia))
    try:
        pad.SetSize(pcbnew.F_Cu, size)
    except TypeError:
        pad.SetSize(size)
    pad.SetDrillSize(VECTOR2I(FromMM(drill), FromMM(drill)))


def seg(a, b, w, layer, n):
    t = pcbnew.PCB_TRACK(board)
    t.SetStart(P(*a))
    t.SetEnd(P(*b))
    t.SetWidth(FromMM(w))
    t.SetLayer(layer)
    t.SetNet(n)
    board.Add(t)


def route(pts, w, layer, n, chamfer=0.6):
    """Polyline of tracks; right-angle corners get a 45 degree chamfer."""
    out = [pts[0]]
    for i in range(1, len(pts) - 1):
        a, p, b = pts[i - 1], pts[i], pts[i + 1]
        v1 = (p[0] - a[0], p[1] - a[1])
        v2 = (b[0] - p[0], b[1] - p[1])
        l1, l2 = math.hypot(*v1), math.hypot(*v2)
        square = abs(v1[0] * v2[0] + v1[1] * v2[1]) < 1e-6
        if square and l1 > 2 * chamfer and l2 > 2 * chamfer:
            out.append((p[0] - v1[0] / l1 * chamfer, p[1] - v1[1] / l1 * chamfer))
            out.append((p[0] + v2[0] / l2 * chamfer, p[1] + v2[1] / l2 * chamfer))
        else:
            out.append(p)
    out.append(pts[-1])
    for a, b in zip(out, out[1:]):
        if math.hypot(a[0] - b[0], a[1] - b[1]) > 1e-6:
            seg(a, b, w, layer, n)


def text(s, x, y, size=1.0, layer=pcbnew.F_SilkS, rot=0.0):
    t = pcbnew.PCB_TEXT(board)
    t.SetText(s)
    t.SetLayer(layer)
    t.SetPosition(P(x, y))
    t.SetTextSize(VECTOR2I(FromMM(size), FromMM(size)))
    t.SetTextThickness(FromMM(max(0.12, size * 0.15)))
    t.SetTextAngleDegrees(rot)
    t.SetHorizJustify(pcbnew.GR_TEXT_H_ALIGN_CENTER)
    t.SetVertJustify(pcbnew.GR_TEXT_V_ALIGN_CENTER)
    if layer in (pcbnew.B_SilkS, pcbnew.B_Fab):
        t.SetMirrored(True)
    board.Add(t)


def ref_text(fp, x, y, size=0.8, visible=True):
    r = fp.Reference()
    r.SetVisible(visible)
    r.SetPosition(P(x, y))
    r.SetTextSize(VECTOR2I(FromMM(size), FromMM(size)))
    r.SetTextThickness(FromMM(0.12))
    r.SetTextAngleDegrees(0)


def model(fp, path, offset=(0, 0, 0), rot=(0, 0, 0)):
    m = pcbnew.FP_3DMODEL()
    m.m_Filename = path
    m.m_Offset = pcbnew.VECTOR3D(*offset)
    m.m_Rotation = pcbnew.VECTOR3D(*rot)
    m.m_Scale = pcbnew.VECTOR3D(1, 1, 1)
    fp.Models().push_back(m)


