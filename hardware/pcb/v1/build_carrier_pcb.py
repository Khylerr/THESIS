def fp_rect(fp, layer, x0, y0, x1, y1, width=0.05):
    s = pcbnew.PCB_SHAPE(fp)
    s.SetShape(pcbnew.SHAPE_T_RECT)
    s.SetLayer(layer)
    s.SetStart(VECTOR2I(FromMM(x0), FromMM(y0)))
    s.SetEnd(VECTOR2I(FromMM(x1), FromMM(y1)))
    s.SetWidth(FromMM(width))
    fp.Add(s)


def prepare_library():
    """Write lib/aisl.pretty from the untouched SnapEDA footprints.

    Changes: 1.7 mm pads / 1.0 mm drills (easier to hand-solder than the SnapEDA
    1.56 / 1.04), 3D models, and for the DevKit a courtyard that only covers the two
    socket rows, because the DevKit itself floats about 11 mm above the carrier.
    """
    os.makedirs(LIB, exist_ok=True)
    for old in os.listdir(LIB):
        os.remove(os.path.join(LIB, old))
    io = pcbnew.PCB_IO_MGR.PluginFind(pcbnew.PCB_IO_MGR.KICAD_SEXP)

    fp = pcbnew.FootprintLoad(LIB_SRC, "MODULE_ESP32-DEVKITC-32D")
    fp.SetFPID(pcbnew.LIB_ID("aisl", "ESP32-DevKitC-32D_socketed"))
    for p in fp.Pads():
        resize(p, 1.7, 1.0)
    for g in list(fp.GraphicalItems()):
        if g.GetLayer() == pcbnew.F_CrtYd:
            fp.Remove(g)
    for x in (-12.7, 12.7):
        fp_rect(fp, pcbnew.F_CrtYd, x - 1.8, -19.76 - 1.8, x + 1.8, 25.96 + 1.8)
    model(fp, SOCK_3D, (-12.7, 19.76, 0))
    model(fp, SOCK_3D, (12.7, 19.76, 0))
    model(fp, *DEVKIT_3D)
    io.FootprintSave(LIB, fp)

    fp = pcbnew.FootprintLoad(LIB_SRC, "MODULE_OC09600")
    fp.SetFPID(pcbnew.LIB_ID("aisl", "MPU6050_GY-521_module"))
    for p in fp.Pads():
        if p.GetNumber() in ("VCC", "GND", "SCL", "SDA", "XDA", "XCL", "AD0", "INT"):
            resize(p, 1.7, 1.0)
    model(fp, HDR8_3D, (-6.33, 8.89, 0))
    model(fp, *MPU_3D)
    io.FootprintSave(LIB, fp)


