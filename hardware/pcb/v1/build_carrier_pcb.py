def zone(layer, name):
    z = pcbnew.ZONE(board)
    z.SetLayer(layer)
    z.SetNet(GND)
    z.SetZoneName(name)
    o = z.Outline()
    o.NewOutline()
    for x, y in ((X_MIN, Y_MIN), (X_MAX, Y_MIN), (X_MAX, Y_MAX), (X_MIN, Y_MAX)):
        o.Append(FromMM(OX + x), FromMM(OY + y))
    for hx, hy in NPTH:
        hole = o.NewHole()          # index must be passed to Append, or the points
        for a in range(0, 360, 15):  # land in the outer outline and KiCad crashes on load
            o.Append(FromMM(OX + hx + ZONE_HOLE_R * math.cos(math.radians(a))),
                     FromMM(OY + hy + ZONE_HOLE_R * math.sin(math.radians(a))), -1, hole)
    z.SetLocalClearance(FromMM(0.3))
    z.SetMinThickness(FromMM(0.25))
    z.SetPadConnection(pcbnew.ZONE_CONNECTION_THERMAL)
    z.SetThermalReliefGap(FromMM(0.4))
    z.SetThermalReliefSpokeWidth(FromMM(0.5))
    board.Add(z)
    return z


