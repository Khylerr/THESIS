for fp in board.GetFootprints():
    by_ref[fp.GetReference()] = fp
    fp.SetPath(pcbnew.KIID_PATH("/" + symbol_uuid(fp.GetReference())))
    fp.SetSheetname("/")
    fp.SetSheetfile(PROJECT + ".kicad_sch")
nc_pads = 0
if os.path.exists(NETLIST):
    import xml.etree.ElementTree as ET
    for net_el in ET.parse(NETLIST).getroot().find("nets"):
        if not net_el.get("name").startswith("unconnected-("):
            continue
        for node in net_el:
            pad = pads(by_ref[node.get("ref")])[node.get("pin")]
            assert pad.GetNetname() == "", (node.get("ref"), node.get("pin"), pad.GetNetname())
            pad.SetNet(net(net_el.get("name")))
            nc_pads += 1
else:
    print("no checks/schematic_netlist.xml: run build_schematic.py first, then this script again",
          file=sys.stderr)

